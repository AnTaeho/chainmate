export const TYPES = Object.keys(SPR);

const SPRPIX = {};
for (const [k, rows] of Object.entries(SPR)) {
  if (rows.length !== SH) throw new Error(`sprite height ${k}`);
  const body = (x, y) => x >= 0 && y >= 0 && x < SW && y < SH && rows[y][x] !== '.';
  const px = [];
  for (let y = 0; y < SH; y++) for (let x = 0; x < SW; x++) {
    const ch = rows[y][x];
    if (ch === '.') {
      if (body(x - 1, y) || body(x + 1, y) || body(x, y - 1) || body(x, y + 1)) px.push([x, y, 'o']);
      continue;
    }
    if (ch === 'd') { px.push([x, y, 'd']); continue; }
    let l = x, r = x;
    while (body(l - 1, y)) l--;
    while (body(r + 1, y)) r++;
    const t = r > l ? (x - l) / (r - l) : 0.5;
    let tone = 'f';
    if (y >= SH - 2) tone = 's';
    else if (r - l >= 2 && t <= 0.28) tone = 'h';
    else if (t >= 0.72) tone = 's';
    if (tone === 'f' && !body(x, y - 1) && t < 0.6) tone = 'h';
    px.push([x, y, tone]);
  }
  SPRPIX[k] = px;
}
export const spritePixels = (type) => SPRPIX[type];

const CACHE = new Map();
// 기물 하나의 캔버스(그림자 포함 16×22)
export function spriteCanvas(type, side) {
  const key = type + side;
  let c = CACHE.get(key);
  if (c) return c;
  c = makeCanvas(SW, SH);
  const ctx = context(c);
  const tone = TONE[side];
  ctx.globalAlpha = 0.35;
  ctx.fillStyle = '#000';
  ctx.fillRect(3, SH - 1, 10, 1);
  ctx.fillRect(2, SH - 2, 12, 1);
  ctx.globalAlpha = 1;
  for (const [i, j, t] of SPRPIX[type]) { ctx.fillStyle = tone[t]; ctx.fillRect(i, j, 1, 1); }
  CACHE.set(key, c);
  return c;
}

// 조각으로 부서질 때 쓰는 몸 색 점들(테두리 빼고)
export function spriteChips(type, side) {
  const tone = TONE[side];
  return SPRPIX[type].filter(([, , t]) => t !== 'o').map(([x, y, t]) => ({ x, y, col: tone[t] }));
}
